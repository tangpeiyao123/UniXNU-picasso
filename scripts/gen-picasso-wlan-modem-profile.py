"""Generate the pil_modem split-image PIN profile (sizes + SHA-256 ONLY) from a
read-only firmware directory. No firmware bytes are emitted or stored. The
generated header pins the identity of modem.mdt + modem.b00..b33 and asserts
the ELF p_filesz contract (filesz==0 parts are absent on disk, not missing).

This is an OFFLINE/reproducibility tool: CI has no private blobs and does not
run it. The generated header is committed; re-running on the pinned firmware
must reproduce it byte-for-byte.
"""
import argparse
import hashlib
from pathlib import Path
import struct

HEADER_HEAD = """// SPDX-License-Identifier: BSD-2-Clause-Patent
// GENERATED by scripts/gen-picasso-wlan-modem-profile.py -- do not edit by hand.
// Sizes + SHA-256 of the Picasso pil_modem split firmware (NO firmware bytes).
// Derived read-only from modem.mdt (9420 B, 35 PH) + modem.b00..b33.
// pins PAS 4, carveout 0x8c000000+0xf800000. b18/b25/b34 have p_filesz==0 and
// are intentionally absent; they are NOT listed here. Re-running the generator
// on the pinned firmware must reproduce this file exactly.
#ifndef PICASSO_WLAN_MODEM_FIRMWARE_PROFILE_H
#define PICASSO_WLAN_MODEM_FIRMWARE_PROFILE_H
#include <stdint.h>
struct picasso_wlan_modem_file { const char *path; uint32_t bytes; uint8_t sha256[32]; };
static const struct picasso_wlan_modem_file picassoWlanModemFiles[] = {
"""

HEADER_TAIL = """};
#define PICASSO_WLAN_MODEM_FILE_COUNT (sizeof(picassoWlanModemFiles)/sizeof(picassoWlanModemFiles[0]))
#endif
"""

def pin(path):
    data = path.read_bytes()
    return path.name, len(data), hashlib.sha256(data).digest()

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--firmware', type=Path, default=Path('D:/k30i-firmware/modem-image'))
    p.add_argument('--output', type=Path, required=True)
    a = p.parse_args()
    fw = a.firmware.resolve()
    mdt = (fw / 'modem.mdt').read_bytes()
    e_entry, e_phoff, _e_shoff, _flags = struct.unpack_from('<IIII', mdt, 24)
    _eh, phentsize, phnum, _sh, _shnum, _str = struct.unpack_from('<HHHHHH', mdt, 40)
    assert e_entry == 0x8c000000 and phentsize == 32 and phnum == 35, 'unexpected modem.mdt ELF contract'

    # pieces[i] = p_filesz of PH i; a part file modem.bNN must exist iff filesz > 0.
    pieces = []
    for i in range(phnum):
        _t, _o, _v, _pa, filesz, _memsz, _fl, _al = struct.unpack_from('<IIIIIIII', mdt, e_phoff + i * phentsize)
        pieces.append(filesz)

    rows = []
    rows.append(pin(fw / 'modem.mdt'))
    for i in range(phnum):
        name = f'modem.b{i:02d}'
        path = fw / name
        if pieces[i] == 0:
            assert not path.exists(), f'{name} has p_filesz==0 but exists on disk'
            continue
        assert path.exists(), f'{name} has p_filesz={pieces[i]} but is absent'
        nm, size, digest = pin(path)
        assert size == pieces[i], f'{name} size {size} != p_filesz {pieces[i]}'
        rows.append((nm, size, digest))

    out = [HEADER_HEAD]
    for name, size, digest in rows:
        byts = ', '.join(f'0x{b:02x}' for b in digest)
        out.append(f'    {{"{name}", {size}u, {{{byts}}}}},\n')
    out.append(HEADER_TAIL)
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(''.join(out), encoding='utf8', newline='\n')
    print(f'wrote {a.output}: {len(rows)} pins ({1 + sum(1 for x in pieces if x)} expected)')

if __name__ == '__main__':
    main()
